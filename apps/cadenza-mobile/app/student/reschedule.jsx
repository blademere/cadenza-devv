import { useState } from 'react';
import { ActivityIndicator, Pressable, RefreshControl, ScrollView, Text, View } from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { chooseStudentSchedule, getStudentSchedule } from '../../services/studentService';
import useMobileResource from '../../hooks/useMobileResource';

const ACCENT = '#0C447C';

export default function StudentReschedule() {
  const { data, loading, error, refresh } = useMobileResource(getStudentSchedule);
  const [expanded, setExpanded] = useState({});
  const [selected, setSelected] = useState({});
  const [saving, setSaving] = useState(null);
  const requests = (data?.schedules || []).filter((item) => item.scheduleRequest?.generatedOptions?.length);

  async function submit(item) {
    const optionIds = selected[item.id] || [];
    if (!optionIds.length || saving) return;
    setSaving(item.id);
    try { await chooseStudentSchedule(item.id, optionIds); await refresh(); }
    finally { setSaving(null); }
  }

  return <SafeAreaView className="flex-1 bg-[#F7F7FB]"><ScrollView contentContainerClassName="px-4 pb-8 pt-4" refreshControl={<RefreshControl refreshing={loading} onRefresh={refresh} />}>
    <Text className="text-2xl font-bold" style={{ color: ACCENT }}>Reschedule</Text>
    <Text className="mt-2 text-gray-500">Choose from replacement schedules generated by Front Desk.</Text>
    {loading && <ActivityIndicator className="mt-6" color={ACCENT} />}
    {!!error && <Text className="mt-4 text-sm text-red-700">{error.message || error}</Text>}
    {!loading && !requests.length && <Text className="mt-6 text-sm text-gray-500">No generated reschedule options yet.</Text>}
    {requests.map((item) => {
      const request = item.scheduleRequest;
      const submitted = request.studentChoices?.length > 0;
      const isExpanded = !!expanded[item.id];
      return <View key={item.id} className="mt-5 rounded-2xl bg-white p-4 shadow-sm">
        <Text className="text-base font-bold" style={{ color: ACCENT }}>{item.courseName || item.lesson || 'Lesson'}</Text>
        <Text className="mt-1 text-sm text-gray-600">Instructor: {item.instructor?.name || 'Instructor'}</Text>
        <Text className="mt-1 text-sm text-gray-600">Current: {item.scheduledStart ? new Date(item.scheduledStart).toLocaleString() : 'Schedule pending'}</Text>
        <Text className="mt-2 text-xs font-semibold uppercase text-amber-700">{submitted ? 'Choices submitted' : 'Action required'}</Text>
        <Pressable onPress={() => setExpanded((value) => ({ ...value, [item.id]: !isExpanded }))} className="mt-4 self-start rounded-xl bg-[#0C447C] px-4 py-3"><Text className="font-semibold text-white">{isExpanded ? 'Hide schedule' : 'See schedule'}</Text></Pressable>
        {isExpanded && <View className="mt-4 border-t border-gray-100 pt-4"><Text className="font-semibold text-gray-800">Generated schedules</Text>
          {request.generatedOptions.map((option) => { const isSelected = (selected[item.id] || []).includes(option.id); const alreadyChosen = request.studentChoices?.includes(option.id); return <Pressable key={option.id} disabled={submitted || !!saving} onPress={() => setSelected((value) => ({ ...value, [item.id]: isSelected ? (value[item.id] || []).filter((id) => id !== option.id) : [...(value[item.id] || []), option.id] }))} className={`mt-2 rounded-xl border p-3 ${isSelected || alreadyChosen ? 'border-green-500 bg-green-50' : 'border-gray-200'}`}><Text className="font-semibold text-gray-900">{option.date} · {option.time}</Text><Text className="mt-1 text-xs text-gray-500">{submitted ? 'Choice submitted' : isSelected ? 'Selected' : 'Tap to select'}</Text></Pressable>; })}
          {!submitted && <Pressable disabled={!!saving || !(selected[item.id] || []).length} onPress={() => submit(item)} className="mt-4 self-start rounded-xl bg-[#0C447C] px-4 py-3"><Text className="font-semibold text-white">{saving === item.id ? 'Submitting...' : 'Submit choices'}</Text></Pressable>}
          <Text className="mt-4 text-sm font-semibold text-amber-800">{submitted ? 'Your choices are submitted. Waiting for instructor approval.' : 'Choose one or more options, then submit your choices.'}</Text>
        </View>}
      </View>;
    })}
  </ScrollView></SafeAreaView>;
}
